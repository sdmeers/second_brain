import os
from datetime import datetime
from backend.vault.writer import atomic_write
from backend.config import OBSIDIAN_VAULT_PATH

def ensure_index_note(folder_path: str, folder_type: str = 'project'):
    folder_name = os.path.basename(folder_path)
    if folder_name.startswith('.') or folder_name.startswith('_'):
        return
        
    index_note_path = os.path.join(folder_path, f"{folder_name}.md")
    if not os.path.exists(index_note_path):
        timestamp = datetime.now().strftime('%Y-%m-%d %H:%M:%S')
        tag = 'project_index' if folder_type == 'project' else 'area_index'
        
        content = f"""---
title: "{folder_name}"
type: {folder_type}
date_created: "{timestamp}"
tags: [{tag}]
---
# {folder_name}

*{folder_type.capitalize()} index note — auto-generated by the AI Librarian.*

---

## Overview
<!-- Add a brief description of this {folder_type} -->

## Key Notes
<!-- Links to important notes in this {folder_type} will appear here -->
"""
        atomic_write(index_note_path, content)
        print(f"Created {folder_type} index note: {index_note_path}")

def backfill_index_notes():
    vault_path = OBSIDIAN_VAULT_PATH
    projects_dir = os.path.join(vault_path, '02_Projects')
    areas_dir = os.path.join(vault_path, '03_Areas')
    
    print("Backfilling project index notes...")
    if os.path.exists(projects_dir):
        for item in os.listdir(projects_dir):
            folder_path = os.path.join(projects_dir, item)
            if os.path.isdir(folder_path):
                ensure_index_note(folder_path, 'project')
                
    print("Backfilling area index notes...")
    if os.path.exists(areas_dir):
        for item in os.listdir(areas_dir):
            folder_path = os.path.join(areas_dir, item)
            if os.path.isdir(folder_path):
                ensure_index_note(folder_path, 'area')
                
    print("Backfill complete.")

if __name__ == "__main__":
    backfill_index_notes()
